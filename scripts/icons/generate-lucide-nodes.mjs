const aliases = {
	"file-minus-2": "FileMinus",
	"file-plus-2": "FilePlus",
	"more-horizontal": "Ellipsis",
};

const toPascalCase = (name) =>
	name
		.split("-")
		.map((part) => `${part.slice(0, 1).toUpperCase()}${part.slice(1)}`)
		.join("");

const nodes = Object.fromEntries(
	iconNames.map((name) => {
		const exportName = aliases[name] ?? toPascalCase(name);
		const component = icons[exportName];
		if (!component) throw new Error(`Missing lucide-react icon: ${name}`);
		const iconNode = component.render({}, null).props.iconNode;
		return [
			name,
			iconNode.map(([tag, attributes]) => [
				tag,
				Object.fromEntries(
					Object.entries(attributes).filter(([key]) => key !== "key")
				),
			]),
		];
	})
);

const output = `/** Generated by scripts/icons/generate-lucide-nodes.mjs. */
export type IconNode = ReadonlyArray<
\treadonly [tag: string, attributes: Readonly<Record<string, string>>]
>;

export const builtinIconNodes: Readonly<Record<string, IconNode>> = ${JSON.stringify(nodes, null, "\t")};
`;

await writeFile(resolve("src/runtime/lucide-nodes.ts"), output);
